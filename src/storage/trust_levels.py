"""SAGE Frozen Memory Trust Levels (M0 to M4).

Document Reference:
- docs/specifications/AEGIS_DATABASE_SCHEMA_ARCHITECTURE.md §4.1
- docs/specifications/AEGIS_DOMAIN_SCHEMA_FOUNDATION.md §4.1

Architectural Invariants:
M0 = Raw Observation (unfiltered observation from sensor, user transcript, or raw tool output)
M1 = Agent Claim (hypothesis or deduction generated by internal cognitive model, unverified)
M2 = Tool-Supported (corroborated by deterministic tool execution or filesystem state)
M3 = Verified (corroborated across multiple independent deterministic tools)
M4 = User-Confirmed (explicitly affirmed, dictated, or corrected by authenticated user)

Non-canonical aliases (e.g., M0_TRANSIENT, M4_AXIOMATIC) are recognized solely for legacy
data normalization; the runtime API strictly stores and requires canonical codes (M0-M4).
"""

from enum import Enum
from typing import Dict


class MemoryTrustLevel(str, Enum):
    """Frozen canonical SAGE memory trust levels (M0 to M4)."""

    M0 = "M0"
    M1 = "M1"
    M2 = "M2"
    M3 = "M3"
    M4 = "M4"


MEMORY_TRUST_LEVEL_SEMANTICS: Dict[str, str] = {
    "M0": "Raw Observation",
    "M1": "Agent Claim",
    "M2": "Tool-Supported",
    "M3": "Verified",
    "M4": "User-Confirmed",
}

NON_CANONICAL_TRUST_ALIASES: Dict[str, str] = {
    "M0_TRANSIENT": "M0",
    "M0_RAW": "M0",
    "M0_RAW_OBSERVATION": "M0",
    "M1_AGENT_CLAIM": "M1",
    "M1_CLAIM": "M1",
    "M1_HYPOTHESIS": "M1",
    "M2_TOOL_SUPPORTED": "M2",
    "M2_TOOL": "M2",
    "M2_CORROBORATED": "M2",
    "M3_VERIFIED": "M3",
    "M3_MULTI_VERIFIED": "M3",
    "M4_AXIOMATIC": "M4",
    "M4_USER_CONFIRMED": "M4",
    "M4_CONFIRMED": "M4",
}


def resolve_trust_level(value: str) -> MemoryTrustLevel:
    """Resolve a trust level string to its canonical MemoryTrustLevel.

    Supports legacy non-canonical aliases for backward compatibility and data
    migration, returning the canonical enum instance.

    Raises:
        ValueError: If value is neither a canonical code nor a recognized alias.
    """
    cleaned = value.strip().upper()
    if cleaned in MemoryTrustLevel._value2member_map_:
        return MemoryTrustLevel(cleaned)

    if cleaned in NON_CANONICAL_TRUST_ALIASES:
        canonical = NON_CANONICAL_TRUST_ALIASES[cleaned]
        return MemoryTrustLevel(canonical)

    valid_options = list(MemoryTrustLevel._value2member_map_.keys())
    raise ValueError(
        f"Invalid trust level '{value}'. Must be one of {valid_options} "
        f"representing frozen canonical levels: {list(MEMORY_TRUST_LEVEL_SEMANTICS.items())}"
    )


def get_trust_level_semantic(level: str | MemoryTrustLevel) -> str:
    """Return the frozen human-readable architectural semantic description for a trust level."""
    key = level.value if isinstance(level, MemoryTrustLevel) else level
    canonical = resolve_trust_level(key).value
    return MEMORY_TRUST_LEVEL_SEMANTICS[canonical]
